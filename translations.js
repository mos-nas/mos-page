const STORAGE_LANG = 'mos-landing-lang';

function i18n(key, lang = 'de') {
  return translations[lang]?.[key] || key;
}

function getAvailableLanguages() {
  return Object.keys(window.languages).filter((lang) => translations[lang]);
}

function detectBrowserLanguage() {
  const available = getAvailableLanguages();
  const preferred = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'de'];
  for (const entry of preferred) {
    const code = String(entry).split(/[-_]/)[0].toLowerCase();
    if (available.includes(code)) return code;
  }
  return available.includes('de') ? 'de' : available[0];
}

function setLanguage(lang) {
  if (!translations[lang]) return;

  try {
    localStorage.setItem(STORAGE_LANG, lang);
  } catch {}

  document.documentElement.setAttribute('lang', lang);

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = i18n(el.getAttribute('data-i18n'), lang);
  });

  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = i18n(el.getAttribute('data-i18n-html'), lang);
  });

  const attributes = {
    'data-i18n-title': 'title',
    'data-i18n-aria-label': 'aria-label',
    'data-i18n-placeholder': 'placeholder',
    'data-i18n-content': 'content',
    'data-i18n-alt': 'alt',
  };
  Object.keys(attributes).forEach((source) => {
    document.querySelectorAll('[' + source + ']').forEach((el) => {
      el.setAttribute(attributes[source], i18n(el.getAttribute(source), lang));
    });
  });

  const titleEl = document.querySelector('title[data-i18n]');
  if (titleEl) document.title = i18n(titleEl.getAttribute('data-i18n'), lang);

  if (typeof window.updateLanguageDisplay === 'function') window.updateLanguageDisplay(lang);
}

function initLanguage() {
  let stored = null;
  try {
    stored = localStorage.getItem(STORAGE_LANG);
  } catch {}
  setLanguage(stored && getAvailableLanguages().includes(stored) ? stored : detectBrowserLanguage());
}
